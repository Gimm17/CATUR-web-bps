function normalizeText(value) {
  if (!value) return '';
  return String(value)
    .toUpperCase()
    .replace(/\s+/g, ' ')
    .trim();
}

const KABUPATEN_BY_NAME = new Map(
  KABUPATEN_LIST.map((item) => [item.nama, item])
);

const KECAMATAN_TO_KABUPATEN = new Map();
for (const [kabName, kecList] of Object.entries(KECAMATAN_BY_KABUPATEN)) {
  const kabMeta = KABUPATEN_BY_NAME.get(kabName);
  if (!kabMeta) continue;
  for (const kecName of kecList) {
    KECAMATAN_TO_KABUPATEN.set(normalizeText(kecName), kabMeta);
    KECAMATAN_TO_KABUPATEN.set(normalizeText(kecName.replace(/\s*-\s*/g, '-')), kabMeta);
  }
}

const KABUPATEN_MATCH_ORDER = [...KABUPATEN_LIST].sort(
  (a, b) => b.nama.length - a.nama.length
);

export function matchKabupatenFromText(rawText) {
  const upper = normalizeText(rawText);
  if (!upper) return null;

  for (const kab of KABUPATEN_MATCH_ORDER) {
    if (
      upper === kab.nama ||
      upper === normalizeText(kab.label) ||
      upper === normalizeText(kab.short_label) ||
      upper === normalizeText(kab.satker_label)
    ) {
      return kab;
    }
    if (kab.aliases.some((alias) => upper === normalizeText(alias))) {
      return kab;
    }
  }

  for (const kab of KABUPATEN_MATCH_ORDER) {
    for (const alias of kab.aliases) {
      const normAlias = normalizeText(alias);
      const regex = new RegExp(`(^|[^A-Z0-9])${normAlias.replace(/[-/\\^$*+?.()|[\]{}]/g, '\\$&')}([^A-Z0-9]|$)`);
      if (regex.test(upper)) {
        return kab;
      }
    }
  }

  return null;
}

export function resolveDaerahKabupaten(daerah) {
  if (!daerah) return null;

  if (daerah.kabupaten_nama && KABUPATEN_BY_NAME.has(normalizeText(daerah.kabupaten_nama))) {
    return KABUPATEN_BY_NAME.get(normalizeText(daerah.kabupaten_nama));
  }

  const namaDaerah = normalizeText(daerah.nama_daerah);
  const titikLokasi = normalizeText(daerah.titik_lokasi);

  if (titikLokasi === 'KECAMATAN' || namaDaerah.startsWith('KECAMATAN ')) {
    const rawKec = namaDaerah.replace(/^KECAMATAN\s+/i, '').trim();
    const byKec =
      KECAMATAN_TO_KABUPATEN.get(rawKec) ||
      KECAMATAN_TO_KABUPATEN.get(rawKec.replace(/\s*-\s*/g, '-'));
    if (byKec) return byKec;
  }

  const byKecDirect =
    KECAMATAN_TO_KABUPATEN.get(namaDaerah) ||
    KECAMATAN_TO_KABUPATEN.get(namaDaerah.replace(/\s*-\s*/g, '-'));
  if (byKecDirect && titikLokasi === 'KECAMATAN') {
    return byKecDirect;
  }

  return matchKabupatenFromText(namaDaerah);
}

export function getLevelWilayah(daerah) {
  if (daerah?.level_wilayah) return daerah.level_wilayah;
  const titik = normalizeText(daerah?.titik_lokasi);
  const nama = normalizeText(daerah?.nama_daerah);
  if (titik === 'KECAMATAN' || nama.startsWith('KECAMATAN ')) {
    return 'kecamatan';
  }
  if (
    titik === 'KABUPATEN' ||
    nama.startsWith('KABUPATEN') ||
    nama === 'KOTA PALU'
  ) {
    return 'kabupaten';
  }
  return 'lainnya';
}

export function resolveWilayahAccess(userOrUnitKerja) {
  if (
    userOrUnitKerja &&
    typeof userOrUnitKerja === 'object' &&
    userOrUnitKerja.wilayah_akses &&
    userOrUnitKerja.wilayah_akses.scope
  ) {
    return userOrUnitKerja.wilayah_akses;
  }

  const rawUnitKerja = typeof userOrUnitKerja === 'string'
    ? userOrUnitKerja
    : (userOrUnitKerja?.unit_kerja || '');

  const norm = normalizeText(rawUnitKerja);
  const matchedKab = matchKabupatenFromText(norm);
  if (matchedKab) {
    return {
      scope: 'kabupaten',
      is_locked: true,
      kdkab: matchedKab.kdkab,
      kode_bps: matchedKab.kode_bps,
      kabupaten_nama: matchedKab.nama,
      kabupaten_label: matchedKab.label,
      satker_label: matchedKab.satker_label,
    };
  }

  return {
    scope: 'provinsi',
    is_locked: false,
    kdkab: null,
    kode_bps: '7200',
    kabupaten_nama: null,
    kabupaten_label: 'Seluruh Kabupaten/Kota',
    satker_label: 'BPS Provinsi Sulawesi Tengah',
  };
}

export function getStoredUserWilayahAccess() {
  try {
    const rawUser = localStorage.getItem('user');
    if (!rawUser) return resolveWilayahAccess(null);
    const parsed = JSON.parse(rawUser);
    return resolveWilayahAccess(parsed);
  } catch {
    return resolveWilayahAccess(null);
  }
}
